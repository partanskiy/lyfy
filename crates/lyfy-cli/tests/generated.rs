mod common;
use common::Fixture;
use serde_json::json;
use std::{fs, process::Command};

#[test]
fn generated_cache_requires_permission_and_reproduces_exact_saved_bytes() {
    let f = Fixture::new();
    for name in ["tmp", "usr/lib", "var/cache/ldconfig"] {
        fs::create_dir_all(f.root.join(name)).unwrap();
    }
    f.write("etc/ld.so.conf", "");
    let status = Command::new("/usr/bin/ldconfig")
        .args(["-X", "-i", "-C", "/etc/ld.so.cache", "-r"])
        .arg(&f.root)
        .status()
        .unwrap();
    assert!(status.success());
    let expected = fs::read(f.root.join("etc/ld.so.cache")).unwrap();
    let resources =
        json!([{"kind":"generated","path":"/etc/ld.so.cache","producer":"ldconfig"}]).to_string();
    f.ok(&["save", "--system_resources", &resources]);
    assert_eq!(
        f.ok(&["save", "--system_resources", &resources])["created"],
        false
    );
    f.write("etc/ld.so.cache", "damaged cache");
    assert_eq!(
        f.run(&["apply", "--overwrite", "true", "--write"])
            .status
            .code(),
        Some(1)
    );
    assert_eq!(f.read("etc/ld.so.cache"), "damaged cache");
    f.ok(&[
        "apply",
        "--regenerate",
        "true",
        "--overwrite",
        "true",
        "--write",
    ]);
    assert_eq!(fs::read(f.root.join("etc/ld.so.cache")).unwrap(), expected);
    assert_eq!(
        f.ok(&["save", "--system_resources", &resources])["created"],
        false
    );
    f.write("etc/ld.so.cache", "not generated by the declared producer");
    let accepted = f.head("laptop");
    assert_eq!(
        f.run(&["save", "--system_resources", &resources])
            .status
            .code(),
        Some(2)
    );
    assert_eq!(f.head("laptop"), accepted);
}
